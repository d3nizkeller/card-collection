-- server/worker/schema.sql — схема базы D1 (b463)
--
-- Вся база — одна таблица-хранилище. Почему так, а не «таблица на каждую сущность»:
--   1. деньги хранятся десятичной строкой в v, поэтому суммы любой величины
--      (ставки до 1e15, банк сайта исторически до 1e17+) не упираются в
--      64-битный INTEGER и не теряют точность;
--   2. ver — версия записи. Любое изменение баланса/банка/лота выполняется как
--      «UPDATE … WHERE ver = ?»: если запись успел поменять другой запрос,
--      изменений будет 0 и store.js повторит операцию. Это и есть защита от
--      гонки (два одновременных срыва джекпота больше не гасят друг друга);
--   3. один и тот же код доменного слоя работает и на D1, и на in-memory
--      драйвере локальных тестов — расхождение исключено.
--
-- Таблица создаётся автоматически при первом запросе (driver-d1.js: ensureSchema).
-- Этот файл — для ручного применения и для документации:
--     npx wrangler d1 execute nexus-bank --remote --file=./schema.sql
--
-- Пространства имён (ns):
--   p        игрок: баланс, блокировка, кирка, гарант, счётчики, награды
--   bank     общий банк сайта (fed/won/floor/wins)
--   hall     зал славы джекпота (последние 40 срывов)
--   jpc      настройки джекпота из Студии (проценты, пол, потолок, вероятности)
--   catalog  каталог комнаты: паки и карты (нужен серверу для честных вскрытий)
--   creds    учётка Студии: логин + PBKDF2-хэш пароля (пароль только здесь)
--   cfg      служебные настройки
--   ops      ключи операций (идемпотентность: повторная доставка не платит дважды)
--   mines    активные раунды мин — раскладка мин клиенту не отдаётся
--   lots     лоты биржи (эскроу: open / sold / cancelled)
--   ledger   квитанции продавцам
--   inv      владение картами: cid:cardId -> copies
--   stats    зеркало реестра игроков для таблицы «Пользователи» в Студии
--   audit    журнал действий админки (кто, кого, когда, что сделал)

CREATE TABLE IF NOT EXISTS kv (
    ns  TEXT NOT NULL,
    k   TEXT NOT NULL,
    v   TEXT,
    ver INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (ns, k)
);

CREATE INDEX IF NOT EXISTS ix_kv_ns ON kv (ns);
CREATE INDEX IF NOT EXISTS ix_kv_ns_k ON kv (ns, k);
